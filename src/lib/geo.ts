/**
 * مدن دولةٍ باسمها.
 *
 * **بلا مطابقةٍ لا قائمة فارغة تُفرض**: تُعاد مصفوفةٌ فارغة، والشاشة تترك
 * الخانة تُكتب — فعميلٌ في مدينة ليست عندنا يُسجَّل ولا يُردّ.
 */
export function citiesOf(country: string | null | undefined): string[] {
  if (!country) return [];
  return COUNTRIES.find((c) => c.name === country)?.cities ?? [];
}

/** هل هذا الاسم دولةٌ نعرفها؟ */
export function isKnownCountry(name: string | null | undefined): boolean {
  return !!name && COUNTRIES.some((c) => c.name === name);
}
