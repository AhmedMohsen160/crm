/**
 * الحذف النهائيّ لسجل عميل — القواعد الخالصة.
 *
 * ── لماذا يوجد أصلًا، والقاعدة تقول «لا شيء يُمحى» ────────────
 *
 * قالها أحمد: **«البيانات التي أقوم بإدخالها كتجربة للسيستم أستطيع حذفها…
 * ويكأنه لم يدخل السيستم أصلًا.»**
 *
 * و§٣ بند ٣ يقول: لا شيء يُمحى — حذفٌ منطقيّ وسجلُّ تدقيق دائم. والقاعدة
 * موضوعةٌ لبيانات المكتب الحقيقية: عميلٌ اشترى لا يُمحى ليختفي أثرُ بيعه.
 * أما ما أُدخل تجربةً فليس بياناتٍ أصلًا — وتركُه يفسد كل عدٍّ وكل ترتيب
 * وكل متوسط، والحذف المنطقيّ يُخفيه من الشاشة ويبقيه في الحساب.
 *
 * **فالاستثناء محدودٌ بأربعة حدود:**
 *   ١) صلاحية `canPurgeRecords` — للمالك ومدير النظام وحدهما.
 *   ٢) جملةٌ تُكتب بالحرف، فلا يُضغط سهوًا.
 *   ٣) جردٌ يُعرض قبل الضغط: كم مشروعًا وكم ليدًا وكم جنيهًا.
 *   ٤) **وسجلُّ التدقيق يبقى** بجرده كاملًا — فما مُحي معروفٌ أنه مُحي،
 *      ومن محاه، ومتى. وهذا ما يجعله حذفًا لا محوًا للأثر.
 *
 * ── وما لا يُحذف مع العميل ────────────────────────────────────
 *
 * **قيدُ دفترٍ مرحَّل في فترةٍ مقفلة لا يُمسّ.** المحاسب أقفل الشهر وبنى
 * عليه ميزانَ مراجعةٍ وقائمةَ دخل؛ وحذفُ قيدٍ منه يغيّر ربحَ شهرٍ مضى بلا
 * أن يعلم أحد. والقيد الخاطئ **يُعكَس بقيد مضادّ** لا يُحذف — وهذا حدُّ
 * §٣ بند ٣ الذي لا يُنقَض.
 *
 * فالحذف يمضي في كل شيء ويتوقّف عند هذا وحده، ويقول للمالك أيَّ فترةٍ
 * تحجبه وكم قيدًا فيها.
 */

/** الجملة التي تُكتب بالحرف قبل الحذف — لا زرَّ تأكيدٍ يُنقر مرورًا */
export const PURGE_PHRASE = 'احذف هذا العميل نهائيًا';

export type PurgeInventory = {
  clientName: string;
  /** ما سيُحذف — الاسم العربيّ والعدد */
  counts: Record<string, number>;
  /** إجمالي ما سُلّم أو حُصّل من مشاريعه — يُقرأ قبل الضغط */
  revenue: number;
  /** قيودٌ مرحَّلة في فتراتٍ مقفلة تحجب الحذف — الفترة وعددُها */
  closedEntries: { period: string; entries: number }[];
  /** قيودٌ مرحَّلة في فتراتٍ مفتوحة — تُحذف ويُقال عددُها */
  postedEntries: number;
  /** وسمُ ترحيلٍ على السجل — يعني أنه جاء من ملفات المكتب لا من تجربة */
  importTag: string | null;
};

export type PurgeVerdict =
  | { ok: true; warnings: string[] }
  | { ok: false; reason: string };

/**
 * هل يمضي الحذف؟
 *
 * **والتحذير ليس منعًا.** سجلٌّ موسومٌ بوسم ترحيل جاء من دفاتر المكتب لا من
 * تجربة، فيُقال ذلك صريحًا ويبقى القرار لمن يملكه — أما الفترة المقفلة فمنعٌ
 * لا تحذير.
 */
export function purgeVerdict(inventory: PurgeInventory): PurgeVerdict {
  if (inventory.closedEntries.length > 0) {
    const detail = inventory.closedEntries
      .map((row) => `${row.period} (${row.entries} قيدًا)`)
      .join('، ');
    return {
      ok: false,
      reason: `لهذا العميل قيودٌ مرحَّلة في فتراتٍ مقفلة: ${detail}. القيد المرحَّل يُعكَس بقيد مضادّ ولا يُحذف — افتح الفترة أو اعكس القيود أولًا`,
    };
  }

  const warnings: string[] = [];
  if (inventory.importTag) {
    warnings.push(
      `هذا السجل جاء من ملفات المكتب بوسم «${inventory.importTag}» — لا من تجربة. وسحبُ الوسم كلَّه من شاشة الترحيل أسلم من حذف بطاقةٍ واحدة منه`
    );
  }
  if (inventory.postedEntries > 0) {
    warnings.push(
      `و${inventory.postedEntries} قيدًا مرحَّلًا في فتراتٍ مفتوحة سيُحذف معه — فيتغيّر ميزان المراجعة لهذه الفترات`
    );
  }
  if (inventory.revenue > 0) {
    warnings.push(
      `وإيرادٌ معترَفٌ به قدرُه ${inventory.revenue.toLocaleString('en-US', { minimumFractionDigits: 2 })} سيسقط من كل تقرير`
    );
  }

  return { ok: true, warnings };
}

/** مجموع ما سيُحذف — يُعرض رقمًا واحدًا فوق الجرد */
export function purgeTotal(counts: Record<string, number>): number {
  return Object.values(counts).reduce((sum, n) => sum + n, 0);
}
