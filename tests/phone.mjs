/**
 * اختبار قاعدة تطبيع الهاتف السباعية — §١٤ من المواصفة.
 *
 * تُشغَّل بلا متصفح ولا قاعدة بيانات، فهي أسرع خط دفاع عن «لا عميل مكرر».
 * التشغيل:  npm run test:phone
 */
import { normalizePhone, NO_PHONE, formatPhone } from '../src/lib/phone.ts';

const results = [];
function expect(input, expected, label) {
  const actual = normalizePhone(input).value;
  const ok = actual === expected;
  results.push({ ok, label });
  console.log(`${ok ? '✓' : '✗'} ${label}${ok ? '' : ` — نتج «${actual}» والمتوقع «${expected}»`}`);
}

console.log('قاعدة التطبيع السباعية — §١٤\n');

// الخطوة ١: حذف كل ما ليس رقمًا
expect('+20 100 123 4567', '201001234567', 'المسافات وعلامة + تُحذف');
expect('0100-123-4567', '201001234567', 'الشرطات تُحذف');
expect('(010) 0123 4567', '201001234567', 'الأقواس تُحذف');

// الخطوة ٢: محارف الاتجاه — بدونها نفقد ~١٠٪ من المطابقات
expect('⁦+201001234567⁩', '201001234567', 'محارف الاتجاه المنسوخة من واتساب تُحذف');
expect('‏01001234567‎', '201001234567', 'علامتا RLM/LRM تُحذفان');

// الخطوة ٣: بادئة 00 الدولية
expect('00201001234567', '201001234567', 'بادئة 00 تُحذف');

// الخطوة ٤: ١١ رقمًا تبدأ بـ01
expect('01001234567', '201001234567', 'الرقم المصري المحلي يأخذ مفتاح 20');

// الخطوة ٥: ١٠ أرقام تبدأ بـ1 — الصفر البادئ ضاع في إكسل
expect('1001234567', '201001234567', 'الرقم الذي فقد صفره البادئ يُستعاد');
expect(
  '201117741994.0',
  '201117741994',
  'الرقم المخزَّن عددًا عشريًا (المثال الحرفي في المواصفة)'
);
expect('1001234567.00', '201001234567', 'كسر عشري بخانتين يُقطع أيضًا');

// الخطوة ٦: ١٢ رقمًا تبدأ بـ20 تُترك
expect('201001234567', '201001234567', 'الرقم بمفتاح الدولة يُترك كما هو');

// الخطوة ٧: القيم غير الصالحة
expect('0', NO_PHONE, 'القيمة صفر ← NO_PHONE');
expect('', NO_PHONE, 'القيمة الفارغة ← NO_PHONE');
expect(null, NO_PHONE, 'القيمة المعدومة ← NO_PHONE');
expect('12345', NO_PHONE, 'أقل من ٨ أرقام ← NO_PHONE');
expect('mona@example.com', NO_PHONE, 'خلية تحمل بريدًا بدل رقم ← NO_PHONE');

// أرقام غير مصرية تُترك كما هي بعد التنظيف
expect('+966 50 123 4567', '966501234567', 'الرقم السعودي يُترك بمفتاحه');

// الأرقام العربية الهندية — يكتبها المستخدمون على الجوال
expect('٠١٠٠١٢٣٤٥٦٧', '201001234567', 'الأرقام العربية تتحول إلى لاتينية');

// نفس العميل بأربع صيغ ← مفتاح واحد. هذا جوهر «لا عميل مكرر».
const variants = ['01001234567', '+20 100 123 4567', '00201001234567', '⁦201001234567⁩'];
const keys = new Set(variants.map((v) => normalizePhone(v).value));
const oneKey = keys.size === 1;
results.push({ ok: oneKey, label: 'أربع صيغ لنفس الرقم تنتج مفتاحًا واحدًا' });
console.log(`${oneKey ? '✓' : '✗'} أربع صيغ لنفس الرقم تنتج مفتاحًا واحدًا (${[...keys].join(', ')})`);

// العرض
const shown = formatPhone('201001234567');
const displayOk = shown === '+20 100 123 4567';
results.push({ ok: displayOk, label: 'العرض المنسّق' });
console.log(`${displayOk ? '✓' : '✗'} العرض المنسّق: ${shown}`);

const failed = results.filter((r) => !r.ok);
console.log(`\n═══ النتيجة: ${results.length - failed.length}/${results.length} نجحت ═══`);
process.exit(failed.length ? 1 : 0);
