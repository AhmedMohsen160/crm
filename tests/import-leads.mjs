/**
 * اختبار قراءة شيت الليدز — «سجل العملاء».
 *
 * وهو الشيت الوحيد الذي يقول ما **خسره** المكتب: ألفٌ وأربعمئة استفسارٍ لم
 * يتحوّل من ألفين ومئة. وخطأٌ فيه لا يُرى في أي رقمٍ ماليّ — الدفتر يبقى
 * متوازنًا والإيراد صحيحًا — ولا يظهر إلا في قرارٍ يُتّخذ على معدل تحويلٍ
 * كاذب أو تكلفة اكتسابٍ كاذبة.
 *
 * التشغيل:  npm run test:import-leads
 */
import {
  findLeadsHeader,
  leadsTag,
  yesNo,
  leadStatusOf,
  parseLeadAmount,
  lossReasonOf,
  leadNameOf,
} from '../src/lib/import-leads.ts';
import { isImportTag } from '../src/lib/import-sales.ts';

const results = [];
function check(ok, label, detail = '') {
  results.push({ ok, label });
  console.log(`${ok ? '✓' : '✗'} ${label}${ok ? '' : ` — ${detail}`}`);
}
function eq(actual, expected, label) {
  check(
    JSON.stringify(actual) === JSON.stringify(expected),
    label,
    `نتج ${JSON.stringify(actual)} والمتوقع ${JSON.stringify(expected)}`
  );
}

// ═══════════════════════════════════════════════════════════════
//  ١ · الترويسة
// ═══════════════════════════════════════════════════════════════

/** ترويسة الملف الحقيقي حرفًا بحرف — وفوقها صفُّ عنوانٍ فيه «Data» وحده */
const HEADER = [
  '#', 'التاريخ', 'اسم العميل', 'رقم الهاتف', 'القناة', 'طريقة التواصل',
  'أدمن المبيعات', 'تم التحويل؟', 'المبلغ المحصل (EGP)', 'الفرع',
  'تمت المتابعة؟', 'سبب الرفض',
];

const found = findLeadsHeader([['Data'], HEADER, []]);
check(found !== null, 'الترويسة تُوجد تحت صفّ العنوان');
eq(found.row, 1, '★ **وصفُّ «Data» ليس ترويسة** — لولا ذلك لقُرئت الصفوف كلها بعمودٍ واحد');
eq(found.columns.date, 1, 'والتاريخ بموضعه');
eq(found.columns.phone, 3, 'والهاتف');
eq(found.columns.converted, 7, 'وعمود التحويل');
eq(found.columns.lossReason, 11, 'وسبب الرفض');

/** والترتيب لو تغيّر تُقرأ الورقة كما هي */
const shuffled = findLeadsHeader([['رقم الهاتف', 'التاريخ', 'الفرع']]);
eq(shuffled.columns.phone, 0, 'ترتيبٌ مقلوب يُقرأ بأسمائه');
eq(shuffled.columns.branch, 2, 'والفرع في موضعه الجديد');

/** ★ والهمزة والتاء المربوطة لا تكسران المطابقة */
const spelled = findLeadsHeader([['التاريخ', 'رقم الهاتف', 'أدمن المبيعات', 'الفرع']]);
eq(spelled.columns.admin, 2, '«أدمن المبيعات» بهمزتها تُطابَق');
const noHamza = findLeadsHeader([['التاريخ', 'رقم الهاتف', 'ادمن المبيعات']]);
eq(noHamza.columns.admin, 2, '★ وبلا همزتها كذلك — والمطابقة مطبَّعة لا حرفيّة');

check(
  findLeadsHeader([['التاريخ', 'مدين', 'الحساب الرئيسي']]) === null,
  'وترويسة الدفتر ليست ترويسة ليدز — فلا تُقرأ ورقةٌ بالأخرى'
);
check(
  findLeadsHeader([['الشهر', 'Google Ads (EGP)', 'Leads', 'CAC (EGP)']]) === null,
  '★ **وورقة «الملخص الشهري» لا تُقرأ** — الإنفاق التسويقي مُدخَلٌ مرة واحدة في الدفتر'
);

// ═══════════════════════════════════════════════════════════════
//  ٢ · «نعم» و«لا» — والفراغ ثالثهما
// ═══════════════════════════════════════════════════════════════

eq(yesNo('نعم'), true, '«نعم» تُقرأ نعم');
eq(yesNo('لا'), false, 'و«لا» لا');
eq(yesNo('Yes'), true, 'وبالإنجليزية كذلك');
/**
 * ★ **والفراغ ليس «لا».** خانةٌ لم تُملأ تعني «لم يُسجَّل» لا «لم يحدث» —
 * و«تمت المتابعة؟» فيها ٣٤ جوابًا من ٢٬١٢٨ صفًّا: لو قُرئ الفارغ «لا»
 * لقال النظام إن ألفين وأربعة وتسعين استفسارًا لم يُتابَع أحدها.
 */
eq(yesNo(''), null, '★ والفراغ ليس «لا» بل «لم يُسجَّل»');
eq(yesNo(null), null, 'والغياب كذلك');
eq(yesNo('ربما'), null, 'وما ليس أحدهما لا يُخمَّن');

// ═══════════════════════════════════════════════════════════════
//  ٣ · حالة الليد
// ═══════════════════════════════════════════════════════════════

eq(leadStatusOf(true), 'WON', 'من تحوّل فائز');
/**
 * ★ **ومن لم يتحوّل خاسرٌ لا جديد.** الشيت سجلٌّ لما مضى: استفسارُ يناير
 * لم يعد مفتوحًا في أغسطس. وإدخالُ ألفٍ وأربعمئة استفسارٍ «جديدة» يملأ
 * طوابير الفريق بموتى ويُنبّههم عليها كل صباح.
 */
eq(leadStatusOf(false), 'LOST', '★ ومن لم يتحوّل خاسرٌ لا جديد');
eq(leadStatusOf(null), 'LOST', 'وما لم يُسجَّل تحوّلُه خاسرٌ كذلك — لم يُبَع شيء');

// ═══════════════════════════════════════════════════════════════
//  ٤ · المبلغ
// ═══════════════════════════════════════════════════════════════

eq(parseLeadAmount(250), 250, 'الرقم يُقرأ كما هو');
eq(parseLeadAmount('1,250.50'), 1250.5, 'وفاصلة الآلاف تُطوى');
eq(parseLeadAmount(''), 0, 'والفراغ صفر');
eq(parseLeadAmount('—'), 0, 'والشرطة كذلك');
eq(parseLeadAmount(-50), 0, 'والسالب لا يُقرأ مبلغًا محصَّلًا');

// ═══════════════════════════════════════════════════════════════
//  ٥ · سبب الرفض والاسم
// ═══════════════════════════════════════════════════════════════

/**
 * ★ **وسبب الرفض يُحفظ نصًّا كما كتبه الأدمن ولا يُصنَّف.**
 *
 * «السعر كان عالي بالنسبة له» و«كان يعتقد أن المكتب مكتب توثيقات وليس مكتب
 * ترجمة» سببان مختلفان تمامًا: الأول تسعير والثاني إعلانٌ يجلب من لا يريد
 * الخدمة أصلًا. وطيُّهما في تصنيفٍ واحد يُخفي أهمّ ما في الشيت.
 */
eq(
  lossReasonOf('كان يعتقد ان المكتب مكتب توثيقات وليس مكتب ترجمة'),
  'كان يعتقد ان المكتب مكتب توثيقات وليس مكتب ترجمة',
  '★ سبب الرفض يُحفظ كما كُتب — لا يُصنَّف ولا يُختصر'
);
eq(lossReasonOf(''), null, 'والفراغ فراغ');
eq(lossReasonOf('  لم يتم الرد  '), 'لم يتم الرد', 'والفراغات الزائدة تُطوى');
eq(lossReasonOf('ط'.repeat(600)).length, 500, 'والطويل يُقصّ عند خمسمئة حرف');

eq(leadNameOf('أحمد'), 'أحمد', 'الاسم يُقرأ حين يُكتب');
eq(leadNameOf(''), null, 'والفارغ غياب');
eq(leadNameOf('—'), null, 'والشرطة غياب');
eq(leadNameOf('غير محدد'), null, '★ و«غير محدد» غيابٌ لا اسم — وإلا صار ألفُ ليدٍ باسمٍ واحد');

// ═══════════════════════════════════════════════════════════════
//  ٦ · الوسم
// ═══════════════════════════════════════════════════════════════

eq(leadsTag(2026), 'leads-2026', 'وسم السنة');
check(isImportTag('leads-2026'), '★ ووسمُ الليدز يُسحب كما يُسحب دفترٌ أو شيت مبيعات');
check(!isImportTag('leads'), 'ووسمٌ بلا سنة لا يُسحب — الحارس صيغتُه');
check(!isImportTag('امسح كل شيء'), 'وكلمةٌ في خانةٍ لا تمسح ما لم يُرحَّل');

const failed = results.filter((r) => !r.ok);
console.log(`\n═══ النتيجة: ${results.length - failed.length}/${results.length} نجحت ═══`);
if (failed.length) console.log(failed.map((f) => `  ✗ ${f.label}`).join('\n'));
process.exit(failed.length ? 1 : 0);
